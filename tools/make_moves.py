"""Generate the keyframe files for the five-leg moves (ring ripple, star step, rock mode).

    uv run python -m tools.make_moves          # writes moves/ring-ripple.toml etc.

The moves are plain keyframe TOML like the hand-written ones; this script only saves typing the
dozens of staggered foot keys. Every move is checked by ``MovePlayer.validate`` in the tests:
joint limits, servo speed, centre of mass 15 mm inside the planted feet, no foot sliding.
"""

from __future__ import annotations

import math
from pathlib import Path

MOVES = Path(__file__).resolve().parent.parent / "moves"
N = 5


def radial(leg: int, r: float) -> tuple[float, float]:
    """World-frame xy offset of `r` mm outward along leg `leg` (legs at 72 deg steps)."""
    a = 2 * math.pi * leg / N
    return r * math.cos(a), r * math.sin(a)


def key(t, x=0.0, y=0.0, z=0.0, roll=0.0, pitch=0.0, yaw=0.0, feet=None):
    return {"t": round(t, 3), "x": x, "y": y, "z": z, "roll": roll, "pitch": pitch, "yaw": yaw,
            "feet": feet or {}}


def write(name: str, comment: str, keys: list[dict]) -> Path:
    lines = [f"# {line}" for line in comment.strip().splitlines()]
    lines += ["# Generated by tools/make_moves.py: edit the generator, not this file.",
              f'name = "{name}"', ""]
    for k in keys:
        lines.append("[[key]]")
        lines.append(f"t = {k['t']}")
        for field, unit in (("x", "x_mm"), ("y", "y_mm"), ("z", "z_mm"), ("roll", "roll_deg"),
                            ("pitch", "pitch_deg"), ("yaw", "yaw_deg")):
            if abs(k[field]) > 1e-9:
                lines.append(f"{unit} = {round(k[field], 2)}")
        for leg in sorted(k["feet"]):
            dx, dy, dz = k["feet"][leg]
            if max(abs(dx), abs(dy), abs(dz)) < 1e-9:
                continue
            lines.append("[[key.foot]]")
            lines.append(f"leg = {leg}")
            for unit, v in (("dx_mm", dx), ("dy_mm", dy), ("dz_mm", dz)):
                if abs(v) > 1e-9:
                    lines.append(f"{unit} = {round(v, 2)}")
        lines.append("")
    path = MOVES / f"{name}.toml"
    path.write_text("\n".join(lines))
    return path


def ring_ripple() -> list[dict]:
    """Each leg lifts and sets down in turn around the ring, like a stadium wave: two laps one
    way, a beat, two faster laps the other way, then a twist to finish. Only one leg is up at a
    time: with five legs, two neighbours up together leave the body outside the other three."""
    LIFT, RISE, LEAN = 45.0, 10.0, 8.0  # the body rises so a lift stays in the knee's range
    keys = [key(0.0), key(0.6, z=RISE)]

    def lap(order, t0, step):
        out, t = [], t0
        for leg in order:
            lx, ly = radial(leg, -LEAN)  # lean away from the lifted leg
            out += [key(t + step, x=lx, y=ly, z=RISE, feet={leg: (0, 0, LIFT)}),
                    key(t + 2 * step, z=RISE)]
            t += 2 * step
        return out, t

    a, t = lap([0, 1, 2, 3, 4] * 2, 0.6, 0.21)
    keys += a
    keys.append(key(t + 0.3, z=RISE))  # beat
    b, t = lap([4, 3, 2, 1, 0] * 2, t + 0.3, 0.16)
    keys += b
    for k, yaw in enumerate((14, -14, 14, 0)):  # finish: twist on the beat
        keys.append(key(t + 0.25 * (k + 1), z=RISE, yaw=yaw))
    keys.append(key(10.0))
    return keys


def star_step() -> list[dict]:
    """Legs step in pentagram order (0, 2, 4, 1, 3), so the feet 'draw' a five-pointed star:
    each leg lifts, reaches out toward its star point, then stamps down while the body dips.
    Once slowly, once faster, then a little bow."""
    keys = [key(0.0)]
    t = 0.3
    for dur in (0.9, 0.72):
        for leg in (0, 2, 4, 1, 3):
            sx, sy = radial(leg, 6.0)  # body leans toward the pointing leg
            rx, ry = radial(leg, 40.0)  # foot reaches out toward its star point
            keys += [
                key(t + 0.25 * dur, x=sx * 0.5, y=sy * 0.5, z=8.0, feet={leg: (0, 0, 25)}),
                key(t + 0.55 * dur, x=sx, y=sy, z=12.0, feet={leg: (rx, ry, 50)}),
                key(t + 0.80 * dur, x=sx * 0.5, y=sy * 0.5, z=8.0, feet={leg: (0, 0, 25)}),
                key(t + dur, z=-8.0),  # stamp
            ]
            t += dur
    keys += [key(t + 0.35, z=-4.0), key(t + 0.75, z=-14.0, pitch=6.0),  # bow toward leg 0
             key(t + 1.1, z=-14.0, pitch=6.0)]
    keys.append(key(10.0))
    return keys


SPREAD, UP = 60.0, 30.0  # feet step this far out to let the body get low; lift height
STEP_SEG = 0.17  # each third of a step (up, across, down); faster trips the servo speed limit


def _step_feet(spread: dict, order, t0: float, seg: float, target: float):
    """Move each foot in `order` to `target` mm out along its leg: straight up, across, straight
    down (a planted foot never slides). Updates `spread` (leg -> xy offset)."""
    out, t = [], t0
    for leg in order:
        old, new = spread.get(leg, (0.0, 0.0)), radial(leg, target)
        base = {lg: (*xy, 0.0) for lg, xy in spread.items()}
        up_old, up_new = dict(base), dict(base)
        up_old[leg], up_new[leg] = (*old, UP), (*new, UP)
        spread[leg] = new
        down = {lg: (*xy, 0.0) for lg, xy in spread.items()}
        out += [key(t + seg, feet=up_old), key(t + 2 * seg, feet=up_new),
                key(t + 3 * seg, feet=down)]
        t += 3 * seg
    return out, t


def rock_mode() -> list[dict]:
    """Rocky becomes a rock: each foot steps out wide, the body sinks until the belly is just
    off the floor and holds still, gives a little shiver, then rises and steps back in."""
    LOW = -60.0
    spread: dict = {}
    keys = [key(0.0)]
    a, t = _step_feet(spread, [0, 1, 2, 3, 4], 0.3, STEP_SEG, SPREAD)
    keys += a
    planted = {lg: (*xy, 0.0) for lg, xy in spread.items()}
    keys += [key(t + 1.2, z=LOW, feet=planted), key(t + 2.2, z=LOW, feet=planted)]  # a rock
    t += 2.2
    for k, yaw in enumerate((2.5, -2.5, 2.5, -2.5, 0.0)):  # shiver
        keys.append(key(t + 0.14 * (k + 1), z=LOW, yaw=yaw, feet=planted))
    t += 0.7
    keys.append(key(t + 1.3, feet=planted))  # rise
    b, t = _step_feet(spread, [4, 3, 2, 1, 0], t + 1.3, STEP_SEG, 0.0)
    keys += b
    keys.append(key(max(10.0, round(t + 0.2, 1))))
    return keys


def rest_mode() -> list[dict]:
    """Rest before power-off (or to charge): feet step out wide and the body lowers until it
    sits on the five hip brackets' lower arms, the lowest points of the body. It rests on its
    own frame, so cutting power can't tip it; the legs just go limp where they are. The clip
    holds still as if powered off, then wakes up and stands."""
    REST = -64.5  # the coxa lower arms (35.3 mm below the hip plane) just touch the floor
    spread: dict = {}
    keys = [key(0.0)]
    a, t = _step_feet(spread, [0, 1, 2, 3, 4], 0.3, STEP_SEG, SPREAD)
    keys += a
    planted = {lg: (*xy, 0.0) for lg, xy in spread.items()}
    keys += [key(t + 1.6, z=REST, feet=planted),
             key(t + 1.6 + 2.5, z=REST, feet=planted)]  # resting / powered off
    t += 4.1
    keys.append(key(t + 1.4, feet=planted))  # wake: stand up
    b, t = _step_feet(spread, [4, 3, 2, 1, 0], t + 1.4, STEP_SEG, 0.0)
    keys += b
    keys.append(key(max(10.0, round(t + 0.3, 1))))
    return keys


def main() -> None:
    for name, fn in (("ring-ripple", ring_ripple), ("star-step", star_step),
                     ("rock-mode", rock_mode), ("rest-mode", rest_mode)):
        print(write(name, fn.__doc__, fn()))


if __name__ == "__main__":
    main()
